#!/bin/bash
# End-to-end harness: real sshd servers in Docker (compose.yaml) and the real
# viperssh client, run from a copy of this working tree under .work/ so your
# own history, vault and ~/.ssh are left alone.
#
#   tests/e2e/run.sh up [ipa]                 build + start the servers (ipa: and FreeIPA), set up the client
#   tests/e2e/run.sh connect HOST [sftp]      connect the way the TUI does after you pick HOST
#   tests/e2e/run.sh tui                      the full TUI, listing the test hosts
#   tests/e2e/run.sh state SERVER STATE       reset bob's password: expired | expiring | ok
#   tests/e2e/run.sh vault PASSWORD|clear [IPA]  set or drop the saved password (E2E or IPA hosts)
#   tests/e2e/run.sh down                     stop the servers and delete .work/
#
# Local accounts (environment E2E): rhel, rhel-jump (ProxyJump), rhel-cmd
# (ProxyCommand ssh -W), rhel-kbd (keyboard-interactive), ubuntu, dead
# (refused), dead-jump (bad bastion).
# IPA account via sssd (environment IPA, needs "up ipa"): ipa (keyboard-
# interactive, IPA's default), ipa-pw (password auth), ipa-jump (password auth
# behind an IPA bastion, which shares the password), ipa-via-local (behind the
# local-account bastion).
# Servers: bastion, rhel, rhel-kbd, ubuntu, ipa. Every login is bob / hunter2,
# and the servers start with bob's password expired (except the bastion).
# The FreeIPA server's first start runs its install (a few minutes); "down"
# keeps its data volume (viperssh-e2e_ipa-data) so later starts are quick.
#
# Behind a TLS-inspecting proxy, set EXTRA_CA_CERT to its CA (defaults to
# $NODE_EXTRA_CA_CERTS) so the image build can reach the package mirrors.

set -e

E2E_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$E2E_DIR/../.." && pwd)"
WORK="$E2E_DIR/.work"
CLIENT="$WORK/viperssh"

export EXTRA_CA_CERT="${EXTRA_CA_CERT:-${NODE_EXTRA_CA_CERTS:-}}"
compose() { docker compose -f "$E2E_DIR/compose.yaml" "$@"; }
# The FreeIPA server sits behind a compose profile so a plain "up" leaves it
# out; commands acting on whatever is running include it
compose_all() { compose --profile ipa "$@"; }

# Run the client copy's python with its lib/ importable
client_py() {
    PYTHONPATH="$CLIENT/lib" "$CLIENT/venv/bin/python3" "$@"
}

# ssh/sftp shims that point the real binaries at our own config and
# known_hosts, so nothing from ~/.ssh is read or written
write_shims() {
    mkdir -p "$WORK/bin"
    for tool in ssh sftp; do
        cat > "$WORK/bin/$tool" <<EOF
#!/bin/sh
exec $(command -v $tool) -F "$WORK/ssh_config" "\$@"
EOF
        chmod +x "$WORK/bin/$tool"
    done
    : > "$WORK/known_hosts"
    cat > "$WORK/ssh_config" <<EOF
# Generated by tests/e2e/run.sh
Host *
    User bob
    UserKnownHostsFile $WORK/known_hosts
    GlobalKnownHostsFile /dev/null
    PubkeyAuthentication no
    IdentityAgent none

Host bastion
    HostName 127.0.0.1
    Port 2220

Host rhel
    HostName 127.0.0.1
    Port 2221

Host rhel-jump
    HostName rhel
    ProxyJump bastion

Host rhel-cmd
    HostName rhel
    ProxyCommand ssh -W %h:22 bastion

Host rhel-kbd
    HostName 127.0.0.1
    Port 2222

Host ubuntu
    HostName 127.0.0.1
    Port 2223

Host dead
    HostName 127.0.0.1
    Port 2229

Host dead-jump
    HostName rhel
    ProxyJump nosuch-bastion.invalid

Host ipa ipa-bastion
    HostName 127.0.0.1
    Port 2224

Host ipa-pw
    HostName 127.0.0.1
    Port 2225

Host ipa-jump
    HostName ipa.example.test
    Port 2222
    ProxyJump ipa-bastion

Host ipa-via-local
    HostName ipa.example.test
    Port 2222
    ProxyJump bastion
EOF
}

# Refresh the client copy from the working tree (keeping its var/ state)
sync_client() {
    if [[ ! -x "$ROOT/venv/bin/python3" ]]; then
        echo "No venv yet - run ./viperssh once to create it." >&2
        exit 1
    fi
    mkdir -p "$CLIENT"
    rsync -a --delete --exclude /var/ --exclude /venv --exclude /.git/ \
        --exclude /etc/hosts.yaml --exclude /tests/e2e/.work/ "$ROOT/" "$CLIENT/"
    ln -sfn "$ROOT/venv" "$CLIENT/venv"
    cat > "$CLIENT/etc/hosts.yaml" <<EOF
environments:
  E2E:
    hosts:
      - rhel
      - rhel-jump
      - rhel-cmd
      - rhel-kbd
      - ubuntu
      - dead
      - dead-jump
  IPA:
    hosts:
      - ipa
      - ipa-pw
      - ipa-jump
      - ipa-via-local
EOF
}

# set_vault PASSWORD|clear [ENV]: saved password for an environment (default
# E2E); the vault unlocks from its master file
set_vault() {
    client_py - "$1" "${2:-E2E}" <<'EOF'
import sys
from vault import Vault
v = Vault()
v.set_enabled(True)
if not v.unlock(v.get_master_from_file() or ""):
    v.create("e2e-master")
    v.write_master_file()
if sys.argv[1] == "clear":
    v.delete_password(sys.argv[2])
else:
    v.set_password(sys.argv[2], sys.argv[1])
EOF
    echo "vault: ${2:-E2E} = $1"
}

# The first start of the FreeIPA server runs its install; wait for it, then
# make sure the IPA user bob exists with an expired password
wait_for_ipa() {
    echo "Waiting for the FreeIPA server (its first start installs it, a few minutes)..."
    for _ in $(seq 150); do
        if compose_all exec -T ipa password-state expired 2>/dev/null; then
            return
        fi
        sleep 5
    done
    echo "FreeIPA didn't come up; see: docker compose -f $E2E_DIR/compose.yaml --profile ipa logs ipa" >&2
    exit 1
}

run_client() {
    cd "$CLIENT"
    PATH="$WORK/bin:$PATH" PYTHONPATH="$CLIENT/lib" exec "$CLIENT/venv/bin/python3" bin/viper.py "$@"
}

case "$1" in
    up)
        if [[ "$2" == "ipa" ]]; then
            compose_all up -d --build --wait
            wait_for_ipa
        else
            compose up -d --build --wait
        fi
        write_shims
        sync_client
        set_vault hunter2 E2E
        set_vault hunter2 IPA
        ;;
    connect)
        [[ -n "$2" ]] || { echo "Usage: $0 connect HOST [sftp]" >&2; exit 1; }
        sync_client
        # --last reconnects to the newest history entry, the same hand-off the
        # TUI makes once you pick a host. The environment keys the saved password.
        client_py - "$2" "${3:-ssh}" <<'EOF'
import sys
from config import Config, History
config = Config()
config.load()
env = next((e for e in config.environments for h in config.get_hosts(e) if h.target == sys.argv[1]), "E2E")
History().add(sys.argv[1], proto=sys.argv[2], env_name=env)
EOF
        run_client --last
        ;;
    tui)
        sync_client
        run_client
        ;;
    state)
        [[ -n "$3" ]] || { echo "Usage: $0 state SERVER expired|expiring|ok" >&2; exit 1; }
        compose_all exec -T "$2" password-state "$3"
        ;;
    vault)
        [[ -n "$2" ]] || { echo "Usage: $0 vault PASSWORD|clear [IPA]" >&2; exit 1; }
        set_vault "$2" "${3:-E2E}"
        ;;
    down)
        compose_all down
        rm -rf "$WORK"
        ;;
    *)
        sed -n '2,/^$/s/^# \{0,1\}//p' "$0"
        exit 1
        ;;
esac
